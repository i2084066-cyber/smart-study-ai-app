            ) {
                Image(
                    painter = painterResource(id = R.drawable.img_study_hero_1794150288556),
                    contentDescription = "Smart Study AI Learning Platform Hero",
                    modifier = Modifier.fillMaxSize(),
                    contentScale = ContentScale.Crop
                )
                Box(
                    modifier = Modifier
                        .fillMaxSize()
                        .background(
                            Brush.verticalGradient(
                                colors = listOf(
                                    Color.Transparent,
                                    Color(0xCC0B1120)
                                )
                            )
